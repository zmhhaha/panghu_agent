from __future__ import annotations
import uuid
from datetime import datetime, timezone
from sqlalchemy import (String, Integer, Boolean, JSON, DateTime, ForeignKey, UniqueConstraint, Index, Text, BigInteger, CheckConstraint, text)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

def uid(): return str(uuid.uuid4())
def now(): return datetime.now(timezone.utc)
class Base(DeclarativeBase): pass
class Project(Base):
    __tablename__='projects'
    id: Mapped[str]=mapped_column(String(36),primary_key=True,default=uid)
    issuer: Mapped[str]=mapped_column(String(512),index=True)
    subject: Mapped[str]=mapped_column(String(256),index=True)
    title: Mapped[str]=mapped_column(String(200))
    settings: Mapped[dict]=mapped_column(JSON,default=dict)
    external_model_ack: Mapped[bool]=mapped_column(Boolean,default=False)
    revision: Mapped[int]=mapped_column(Integer,default=1)
    stage: Mapped[str]=mapped_column(String(40),default='draft')
    active_job_id: Mapped[str|None]=mapped_column(String(36))
    confirmed_plan_revision: Mapped[int|None]=mapped_column(Integer)
    latest_version_id: Mapped[str|None]=mapped_column(String(36))
    deletion_requested: Mapped[bool]=mapped_column(Boolean,default=False)
    cleanup_ready: Mapped[bool]=mapped_column(Boolean,default=False)
    created_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now)
class Asset(Base):
    __tablename__='assets'
    id: Mapped[str]=mapped_column(String(36),primary_key=True,default=uid)
    project_id: Mapped[str]=mapped_column(ForeignKey('projects.id'),index=True)
    storage_key: Mapped[str]=mapped_column(String(512),unique=True)
    display_name: Mapped[str]=mapped_column(String(200))
    sha256: Mapped[str]=mapped_column(String(64))
    media_type: Mapped[str]=mapped_column(String(100))
    bytes: Mapped[int]=mapped_column(BigInteger)
    parse_status: Mapped[str]=mapped_column(String(30),default='queued')
    removed: Mapped[bool]=mapped_column(Boolean,default=False)
    parse_attempt: Mapped[int]=mapped_column(Integer,default=0,server_default=text('0'))
    parse_token: Mapped[str|None]=mapped_column(String(36))
    parse_scope_uid: Mapped[str|None]=mapped_column(String(36))
    parse_lease_until: Mapped[datetime|None]=mapped_column(DateTime(timezone=True))
    parse_error: Mapped[str|None]=mapped_column(String(60))
    text_summary: Mapped[str|None]=mapped_column(String(2000))
class Checkpoint(Base):
    __tablename__='checkpoints'
    id: Mapped[str]=mapped_column(String(36),primary_key=True,default=uid)
    project_id: Mapped[str]=mapped_column(ForeignKey('projects.id'))
    issuer: Mapped[str]=mapped_column(String(512))
    subject: Mapped[str]=mapped_column(String(256))
    storage_key: Mapped[str]=mapped_column(String(512),unique=True)
    manifest: Mapped[dict]=mapped_column(JSON)
    created_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now)
class Plan(Base):
    __tablename__='plans'
    __table_args__=(UniqueConstraint('project_id','revision'),)
    id: Mapped[str]=mapped_column(String(36),primary_key=True,default=uid)
    project_id: Mapped[str]=mapped_column(ForeignKey('projects.id'),index=True)
    revision: Mapped[int]=mapped_column(Integer)
    phase: Mapped[str]=mapped_column(String(30))
    input_snapshot_hash: Mapped[str]=mapped_column(String(64))
    outline: Mapped[dict]=mapped_column(JSON)
    design: Mapped[dict]=mapped_column(JSON)
    user_feedback: Mapped[str]=mapped_column(Text,default='')
    checkpoint_id: Mapped[str]=mapped_column(ForeignKey('checkpoints.id'))
    confirmation_selection: Mapped[dict|None]=mapped_column(JSON)
    confirmed_at: Mapped[datetime|None]=mapped_column(DateTime(timezone=True))
class Job(Base):
    __tablename__='jobs'
    __table_args__=(Index('uq_project_active_job','project_id',unique=True,postgresql_where=text("status IN ('queued','starting','running','collecting','validating','cancelling')"),sqlite_where=text("status IN ('queued','starting','running','collecting','validating','cancelling')")),)
    id: Mapped[str]=mapped_column(String(36),primary_key=True,default=uid)
    project_id: Mapped[str]=mapped_column(ForeignKey('projects.id'),index=True)
    issuer: Mapped[str]=mapped_column(String(512))
    subject: Mapped[str]=mapped_column(String(256))
    kind: Mapped[str]=mapped_column(String(30))
    stage: Mapped[str]=mapped_column(String(30))
    status: Mapped[str]=mapped_column(String(30),default='queued',index=True)
    input_snapshot: Mapped[dict]=mapped_column(JSON)
    base_version_id: Mapped[str|None]=mapped_column(String(36))
    checkpoint_id: Mapped[str|None]=mapped_column(String(36))
    attempt: Mapped[int]=mapped_column(Integer,default=1)
    fencing_token: Mapped[int]=mapped_column(BigInteger,default=0)
    lease_until: Mapped[datetime|None]=mapped_column(DateTime(timezone=True))
    deadline: Mapped[datetime|None]=mapped_column(DateTime(timezone=True))
    session_id: Mapped[str|None]=mapped_column(String(200))
    run_id: Mapped[str|None]=mapped_column(String(200))
    job_uid: Mapped[str|None]=mapped_column(String(200))
    stopped: Mapped[bool]=mapped_column(Boolean,default=False)
    event_cursor: Mapped[int]=mapped_column(Integer,default=0)
    event_floor: Mapped[int]=mapped_column(Integer,default=0)
    error_code: Mapped[str|None]=mapped_column(String(60))
    created_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now)
class ExecutionSlot(Base):
    __tablename__='execution_slots'
    __table_args__=(CheckConstraint('id = 1'),)
    id: Mapped[int]=mapped_column(Integer,primary_key=True,default=1)
    job_id: Mapped[str|None]=mapped_column(String(36))
    fencing_token: Mapped[int]=mapped_column(BigInteger,default=0)
class JobEvent(Base):
    __tablename__='job_events'
    job_id: Mapped[str]=mapped_column(ForeignKey('jobs.id'),primary_key=True)
    seq: Mapped[int]=mapped_column(Integer,primary_key=True)
    type: Mapped[str]=mapped_column(String(60))
    payload: Mapped[dict]=mapped_column(JSON)
    created_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now)
class Version(Base):
    __tablename__='versions'
    id: Mapped[str]=mapped_column(String(36),primary_key=True,default=uid)
    project_id: Mapped[str]=mapped_column(ForeignKey('projects.id'),index=True)
    job_id: Mapped[str]=mapped_column(ForeignKey('jobs.id'),unique=True)
    issuer: Mapped[str]=mapped_column(String(512))
    subject: Mapped[str]=mapped_column(String(256))
    parent_version_id: Mapped[str|None]=mapped_column(String(36))
    checkpoint_id: Mapped[str]=mapped_column(ForeignKey('checkpoints.id'))
    manifest: Mapped[dict]=mapped_column(JSON)
    artifact_root: Mapped[str]=mapped_column(String(512))
    status: Mapped[str]=mapped_column(String(20),default='published')
    created_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now)
class IdempotencyKey(Base):
    __tablename__='idempotency_keys'
    issuer: Mapped[str]=mapped_column(String(512),primary_key=True)
    subject: Mapped[str]=mapped_column(String(256),primary_key=True)
    route: Mapped[str]=mapped_column(String(300),primary_key=True)
    key: Mapped[str]=mapped_column(String(128),primary_key=True)
